// CareMap Facilities Data
// All facilities, wait times, locations, and need options for the CareMap feature.
// Facilities marked isDemo: false have verified names and approximate locations.
// Facilities marked isDemo: true are fictional demonstration facilities.

export type FacilityType =
  | 'AE'
  | 'UTC'
  | 'MIU'
  | 'WalkIn'
  | 'Pharmacy'
  | 'OOH_GP'
  | 'SexualHealth'
  | 'MentalHealth'
  | 'EmergencyDental';

export type Nation = 'wales' | 'england' | 'scotland' | 'northern-ireland';

export type NeedCategory =
  | 'injury'
  | 'illness'
  | 'dental'
  | 'sexual-health'
  | 'mental-health'
  | 'pharmacy';

export type DataStatus = 'simulated' | 'historical' | 'estimated' | 'verified' | 'unavailable';

export interface OpeningHours {
  mon?: [string, string] | null;
  tue?: [string, string] | null;
  wed?: [string, string] | null;
  thu?: [string, string] | null;
  fri?: [string, string] | null;
  sat?: [string, string] | null;
  sun?: [string, string] | null;
  alwaysOpen?: boolean;
}

export interface Facility {
  id: string;
  name: string;
  type: FacilityType;
  lat: number;
  lng: number;
  address: string;
  postcode: string;
  nation: Nation;
  phone?: string;
  openingHours: OpeningHours;
  capabilities: string[];
  limitations: string[];
  isDemo: boolean;
  demoNote?: string;
}

export interface WaitTimeRecord {
  facilityId: string;
  waitMinutes: number | null;
  metricDefinition: string;
  observedAt: string;
  sourceLabel: string;
  dataStatus: DataStatus;
  isSimulated: boolean;
}

export interface DemoLocation {
  id: string;
  name: string;
  postcode: string;
  lat: number;
  lng: number;
  region: string;
}

export interface NeedOption {
  id: NeedCategory;
  label: string;
  icon: string;
  examples: string[];
  emergencyKeywords: string[];
  urgentKeywords: string[];
}

